// UpdateAssessmentModelDefinitionRequest is the canonical DefinitionV2 wire
// contract. Published payloads are generated by the application service and
// are never accepted from REST authoring callers.
type UpdateAssessmentModelDefinitionRequest domain.Definition

// UnmarshalJSON rejects retired authoring fields at the REST boundary, including
// null and empty values. Internal historical Definition decoding is unchanged.
func (r *UpdateAssessmentModelDefinitionRequest) UnmarshalJSON(data []byte) error {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	for field := range fields {
		if strings.EqualFold(field, "DecisionSpec") || strings.EqualFold(field, "InterpretationAssets") {
			return errors.WithCode(code.ErrInvalidArgument, "%s is derived; submit only Measure, Calibration, Execution, Conclusions, Outcomes and ReportMap", field)
		}
	}
	var value domain.Definition
	if err := json.Unmarshal(data, &value); err != nil {
		return err
	}
	*r = UpdateAssessmentModelDefinitionRequest(value)
	return nil
}

